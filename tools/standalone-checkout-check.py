#!/usr/bin/env python3
"""Compare real Git checkout filters (autocrlf false/true), without creating refs.

By default the temporary index contains the current worktree. --baseline uses
HEAD only. The repository index, branches, approved SVG blobs and worktree are
never changed. This verifies Git checkout portability, not a native Windows run.
"""
import argparse
import hashlib
import importlib.util
import json
import os
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--baseline', action='store_true')
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args()
    outputs = []
    with tempfile.TemporaryDirectory(prefix='micro-checkout-') as directory:
        scratch = Path(directory)
        env = os.environ.copy()
        env['GIT_INDEX_FILE'] = str(scratch/'index')
        subprocess.run(['git','read-tree','HEAD'],cwd=ROOT,env=env,check=True)
        if not args.baseline:
            subprocess.run(['git','add','--all'],cwd=ROOT,env=env,check=True,capture_output=True)
        for autocrlf in ('false','true'):
            target = scratch/autocrlf
            target.mkdir()
            subprocess.run(['git','--git-dir='+str(ROOT/'.git'),'--work-tree='+str(target),
                            '-c','core.autocrlf='+autocrlf,'checkout-index','--all',
                            '--prefix='+str(target)+'/'],cwd=ROOT,env=env,check=True,capture_output=True)
            path = target/'tools/build-ui-system-showcase-standalone.py'
            spec = importlib.util.spec_from_file_location('builder_'+autocrlf,path)
            builder = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(builder)
            content = builder.build_html().encode('utf-8')
            logo = (target/'assets/brand/micro-logo/v2/variants/full-color/micro-lockup-arabic.svg').read_bytes()
            outputs.append(dict(autocrlf=autocrlf,sha256=hashlib.sha256(content).hexdigest(),
                                logoCRLF=logo.count(b'\r\n'),logoSHA256=hashlib.sha256(logo).hexdigest()))
    equal = outputs[0]['sha256'] == outputs[1]['sha256']
    report = dict(input='HEAD' if args.baseline else 'worktree via temporary index',
                  startingCommit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),
                  equal=equal,checkouts=outputs)
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(report,indent=2)+'\n')
    print(('PASS' if equal else 'FAIL')+' identical generated bytes across autocrlf=false/true')
    print(json.dumps(report))
    return not equal


if __name__ == '__main__':
    raise SystemExit(main())
