// ---------------------------------------------------------------------------
// SVG -> JSX
// ---------------------------------------------------------------------------

const ATTR_MAP = {
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
  'fill-opacity': 'fillOpacity',
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-dasharray': 'strokeDasharray',
  'stroke-dashoffset': 'strokeDashoffset',
  'stroke-opacity': 'strokeOpacity',
  'clip-path': 'clipPath',
  class: 'className',
};

function convertAttrs(attrs) {
  return attrs.replace(/([a-zA-Z:][\w:.-]*)="([^"]*)"/g, (match, name, value) => {
    // Drop editor-namespaced attributes (inkscape:*, sodipodi:*) — React's
    // SVG types do not accept them and they carry no rendering information.
    if (name.includes(':')) return '';
    const jsxName = ATTR_MAP[name] ?? name;
    return `${jsxName}="${value}"`;
  });
}

/** Convert the inner markup of an <svg> to JSX source (indentation preserved). */
function svgInnerToJsx(inner, indent) {
  return inner
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0)
    .map((line) => {
      let out = line.replace(/<([a-zA-Z:][\w:-]*)((?:\s+[a-zA-Z:][\w:.-]*="[^"]*")*)(\s*\/?>)/g,
        (m, tag, attrs, close) => `<${tag}${convertAttrs(attrs)}${close}`);
      out = out.replace(/<\/([a-zA-Z:][\w:-]*)>/g, '</$1>');
      return `${indent}${out}`;
    })
    .join('\n');
}

function phosphorInner(weight, name) {
  // regular assets are plain names; other weights carry a -<weight> suffix.
  const file =
    weight === 'regular'
      ? join(phosphorRoot, 'regular', `${name}.svg`)
      : join(phosphorRoot, weight, `${name}-${weight}.svg`);
  if (!existsSync(file)) throw new Error(`Phosphor asset missing: ${file}`);
  const svg = readFileSync(file, 'utf8');
  const open = svg.indexOf('>', svg.indexOf('<svg'));
  const close = svg.lastIndexOf('</svg>');
  return svg.slice(open + 1, close);
}

function pascal(semantic) {
  return semantic.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
}

// ---------------------------------------------------------------------------
// Component templates
// ---------------------------------------------------------------------------

function iconComponent(icon) {
  const name = `${pascal(icon.semantic)}Icon`;
  const weightUnion = icon.weights.map((w) => `'${w}'`).join(' | ');
  const defaultWeight = icon.weights[0];
  const paths = icon.weights
    .map((weight) => {
      const jsx = svgInnerToJsx(phosphorInner(weight, icon.phosphor), '    ');
      return `  ${weight}: (\n${jsx}\n  ),`;
    })
    .join('\n');
  const flipNote = icon.flip
    ? 'RTL: directional — adds .mds-icon-flip (BRIEF 23.23).'
    : 'RTL: not directional — never flipped (BRIEF 23.23).';
  const classes = icon.flip
    ? `['mds-icon', 'mds-icon-flip', className]`
    : `['mds-icon', className]`;
  return `${HEADER}// Semantic: ${icon.semantic} · Phosphor: ${icon.phosphor} · weights: ${icon.weights.join(' | ')}.
// Default size ${icon.size} (BRIEF 23.23). ${flipNote}
import type { SVGProps } from 'react';
import type { IconSize } from '../tokens/tokens';

const PATHS = {
${paths}
} as const;

export interface ${name}Props extends Omit<SVGProps<SVGSVGElement>, 'children' | 'width' | 'height'> {
  /** Icon size in px — BRIEF 5.5 sizes (28 exists for the ask symbol family). */
  size?: IconSize;
  /** Drawing weight — only the weights specified for this icon (BRIEF 23.23). */
  weight?: ${weightUnion};
}

export function ${name}({
  size = ${icon.size},
  weight = '${defaultWeight}',
  className,
  ...rest
}: ${name}Props) {
  return (
    <svg
      viewBox="0 0 256 256"
      fill="currentColor"
      width={size}
      height={size}
      aria-hidden="true"
      className={${classes}.filter(Boolean).join(' ')}
      {...rest}
    >
      {PATHS[weight]}
    </svg>
  );
}
`;
}

// The favicon colors map 1:1 to brand tokens (identical hex values in
// tokens.json); tokens are referenced so no raw color lands in src.
const FAVICON_COLOR_MAP = {
  '#164D59': 'var(--mds-color-brand-logo)',
  '#D97757': 'var(--mds-color-brand-signal)',
  '#507F8B': 'var(--mds-color-brand-data)',
};

function askSymbolSource() {
  const svg = readFileSync(faviconPath, 'utf8');
  // The favicon nests an inner <svg> with the same viewBox; its <g> child is
  // the symbol. Title/desc/metadata are documentation, not rendering content.
  const innerSvgOpen = svg.lastIndexOf('<svg');
  const open = svg.indexOf('>', innerSvgOpen);
  const close = svg.lastIndexOf('</svg>');
  let inner = svg.slice(open + 1, close);
  inner = inner
    .replace(/<title[\s\S]*?<\/title>/g, '')
    .replace(/<desc[\s\S]*?<\/desc>/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata>/g, '')
    .replace(/<\/svg>\s*$/, '') // the inner svg's own closing tag
    .trim();
  let jsx = svgInnerToJsx(inner, '  ');
  for (const [hex, cssVar] of Object.entries(FAVICON_COLOR_MAP)) {
    jsx = jsx.replaceAll(`fill="${hex}"`, `fill="${cssVar}"`);
  }
  return jsx;
}

