function typesTs() {
  return `${HEADER}
/**
 * Phosphor drawing weights (BRIEF 5.5). Each generated icon narrows this to
 * exactly the weights its row in BRIEF 23.23 specifies.
 */
export type IconWeight = 'thin' | 'light' | 'regular' | 'bold' | 'fill' | 'duotone';
`;
}

function indexTs() {
  const lines = [HEADER];
  lines.push("export type { IconWeight } from './types';");
  lines.push('');
  lines.push(`export { AskSymbolIcon } from './AskSymbolIcon';`);
  lines.push(`export type { AskSymbolIconProps } from './AskSymbolIcon';`);
  for (const icon of ICONS) {
    const name = `${pascal(icon.semantic)}Icon`;
    lines.push(`export { ${name} } from './${name}';`);
    lines.push(`export type { ${name}Props } from './${name}';`);
  }
  lines.push('');
  lines.push('/** Semantic names that flip horizontally in RTL (BRIEF 23.23 + 5.5 transfer). */');
  lines.push(`export const RTL_FLIP_ICONS: readonly string[] = ${JSON.stringify(RTL_FLIP_ICONS)};`);
  lines.push('');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Write / check
// ---------------------------------------------------------------------------

mkdirSync(assetsDir, { recursive: true });

/** All generated files: [relative path, content]. */
function outputs() {
  const files = ICONS.map((icon) => {
    const name = `${pascal(icon.semantic)}Icon`;
    return [join(iconsDir, `${name}.tsx`), iconComponent(icon)];
  });
  files.push([join(iconsDir, 'AskSymbolIcon.tsx'), askSymbolComponent()]);
  files.push([join(iconsDir, 'types.ts'), typesTs()]);
  files.push([join(iconsDir, 'icons.css'), iconsCss()]);
  files.push([join(iconsDir, 'index.ts'), indexTs()]);
  files.push([join(assetsDir, 'ask-symbol.svg'), readFileSync(faviconPath, 'utf8')]);
  return files;
}

const check = process.argv.includes('--check');
let failed = false;

for (const [path, content] of outputs()) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (check) {
    if (current !== content) {
      failed = true;
      console.error(`[icons:check] MISMATCH: ${path}${current === null ? ' (missing)' : ''}`);
    } else {
      console.log(`[icons:check] OK: ${path}`);
    }
  } else {
    writeFileSync(path, content, 'utf8');
    console.log(`[icons] wrote ${path}`);
  }
}

// Stale generated icon files (renamed/removed specs) must not linger —
// but never touch test files, which live next to the generated code.
const expected = new Set(outputs().map(([path]) => path));
const stale = readdirSync(iconsDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && /^[\w]+Icon\.tsx$/.test(entry.name))
  .map((entry) => join(iconsDir, entry.name))
  .filter((path) => !expected.has(path));
if (stale.length > 0) {
  if (check) {
    failed = true;
    for (const path of stale) console.error(`[icons:check] STALE: ${path}`);
  } else {
    for (const path of stale) {
      rmSync(path);
      console.log(`[icons] removed stale ${path}`);
    }
  }
}

if (check && failed) {
  console.error('[icons:check] FAILED — run `npm run icons` to regenerate.');
  process.exit(1);
}
if (!check) {
  console.log(`[icons] ${ICONS.length} phosphor icons + ask symbol; RTL flip: ${RTL_FLIP_ICONS.join(', ')}`);
}
