#!/usr/bin/env node
/**
 * generate-tokens.mjs — the single bridge between docs/design-system/tokens.json
 * (BRIEF appendix A, the only source of design values) and the library code.
 *
 * Outputs (deterministic, fixed key order taken from the JSON file itself):
 *   src/tokens/tokens.css         — :root { --mds-*: … } custom properties
 *   src/tokens/tokens.ts          — typed `tokens` object + getToken() + helper types
 *   src/tokens/tailwind-theme.css — Tailwind 4 @theme bindings (var() references only)
 *
 * `--check` regenerates everything in memory and byte-compares with the files on
 * disk; any difference exits 1 with a diff list (used by `npm run tokens:check`).
 *
 * Emission rules (mirrored from the batch-1 plan and BRIEF appendix A header):
 * - Path with dashes: color.canvas -> --mds-color-canvas; leaves are flattened
 *   (motion.press-in.ms -> --mds-motion-press-in-ms).
 * - type.*: size and line in rem (÷16); weight unitless; font as a var() name
 *   pointing at --mds-font-display / --mds-font-text.
 * - Numeric arrays: one variable per element, value as suffix
 *   (space -> --mds-space-4…56; size.icon -> --mds-size-icon-14…24).
 * - Non-numeric arrays (size.sheet-height, size.skeleton-widths): NOT emitted as
 *   CSS vars — they only exist in tokens.ts (CSS cannot consume them usefully).
 * - Booleans: not emitted as CSS vars (tokens.ts only) — see motion.growth.once.
 * - Units: colors as-is; layout/radius/border/size numbers in px (radius.full is
 *   9999 -> 9999px); layer / easing / quality / breakpoint unitless; motion.ms
 *   and ms-like motion keys in ms; px-like motion keys (tab-shift, enter-shift,
 *   *-px) in px; font.* as written in the JSON.
 * - role.* values are token NAMES, so they are emitted as resolved references:
 *   --mds-role-focus-ring: var(--mds-color-brand-text). tokens.ts keeps the bare
 *   name. (A bare name would be invalid CSS; this is the only value transform.)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const dsRoot = join(scriptDir, '..');
const repoRoot = join(dsRoot, '..');
const tokensJsonPath = join(repoRoot, 'docs', 'design-system', 'tokens.json');

const HEADER = (target) => `/* GENERATED FILE — DO NOT EDIT.
 * Generated by ds/tools/generate-tokens.mjs from docs/design-system/tokens.json
 * (BRIEF v1.5 appendix A). Regenerate with \`npm run tokens\`; verify with
 * \`npm run tokens:check\` (byte-exact regeneration).
 * Target: ${target}
 */
`;

// ---------------------------------------------------------------------------
// Unit rules
// ---------------------------------------------------------------------------

const MOTION_MS_KEYS = new Set(['ms', 'show-after', 'min-visible', 'pause', 'with-action-ms']);
const MOTION_PX_KEYS = new Set(['tab-shift', 'enter-shift', 'press-cancel-px']);

function motionLeafUnit(key) {
  // velocity-px-per-ms is a ratio (px per ms), not a duration.
  if (key === 'velocity-px-per-ms') return '';
  if (MOTION_MS_KEYS.has(key) || key.endsWith('-ms')) return 'ms';
  if (MOTION_PX_KEYS.has(key) || key.endsWith('-px')) return 'px';
  return '';
}

/**
 * CSS value for a scalar leaf at `path` (array of path segments).
 * Returns null when the leaf must not become a CSS variable.
 */
function cssValue(path, value) {
  const [section, , , leafKey = ''] = [path[0], path[1], path[2], path[path.length - 1]];
  if (typeof value === 'boolean') return null;
  if (typeof value === 'string' && section === 'type' && leafKey === 'font') {
    // type.*.font names a font stack -> var() pointing at --mds-font-display / -text.
    return `var(--mds-font-${value})`;
  }
  if (typeof value === 'number') {
    switch (section) {
      case 'font':
        return String(value);
      case 'type':
        // size / line / size-by-mark values are font sizes -> rem; weight unitless.
        return leafKey === 'weight' ? String(value) : `${value / 16}rem`;
      case 'space':
      case 'layout':
      case 'radius':
      case 'border':
      case 'size':
        return `${value}px`;
      case 'layer':
      case 'breakpoint':
      case 'quality':
        return String(value);
      case 'motion':
        return `${value}${motionLeafUnit(leafKey)}`;
      default:
        return String(value);
    }
  }
  // Strings.
  if (section === 'role') {
    // Role values name another token (color namespace) -> resolved var reference.
    return `var(--mds-color-${value})`;
  }
  return value;
}

function cssVarName(path) {
  return `--mds-${path.join('-')}`;
}

function formatCssNumber(n) {
  return Number.isInteger(n) ? String(n) : String(n);
}

// ---------------------------------------------------------------------------
// CSS generation
// ---------------------------------------------------------------------------

const SECTION_COMMENTS = {
  color: 'Colors (BRIEF 5.2) — hex / rgb() values as written in tokens.json.',
  role: 'Semantic roles (BRIEF appendix A) — references into the color namespace.',
  font: 'Font stacks and font rules (BRIEF 5.3).',
  type: 'Type scale (BRIEF 5.3) — sizes and line heights in rem (16px = 1rem).',
  space: 'Spacing scale (BRIEF 7) — the only allowed spacing values.',
  layout: 'Layout distances (BRIEF 6 / 23).',
  radius: 'Corner radii (BRIEF 5.4).',
  border: 'Border widths (BRIEF 23.19 — every border is 1px except focus states).',
  elevation: 'Elevations (BRIEF 6) — only floating layers get a shadow.',
  layer: 'Layer z-index scale (BRIEF 23.15) — no value outside this table.',
  size: 'Component sizes (BRIEF 23.20 and component specs).',
  motion: 'Motion durations and parameters (BRIEF 7 / 23.14).',
  breakpoint: 'Breakpoints (BRIEF 7) — unitless px values, used from tokens.ts.',
  quality: 'Quality gates (BRIEF 27 / 29) — used from tokens.ts.',
};

function generateTokensCss(json) {
  const lines = [HEADER('CSS custom properties on :root'), '', ':root {'];
  for (const [section, sectionValue] of Object.entries(json)) {
    lines.push(`  /* ${SECTION_COMMENTS[section] ?? section} */`);
    emitSection(section, sectionValue, []);
    lines.push('');
  }
  lines.pop(); // drop the trailing blank line added by the last section
  lines.push('}');
  lines.push('');

  function emitSection(name, value, parentPath) {
    const path = [...parentPath, name];
    if (Array.isArray(value)) {
      if (value.every((el) => typeof el === 'number')) {
        for (const el of value) {
          const varName = `${cssVarName(path)}-${formatCssNumber(el)}`;
          lines.push(`  ${varName}: ${cssValue(path, el)};`);
        }
      } else {
        lines.push(
          `  /* ${path.join('.')} = ${JSON.stringify(value)} — not emitted as CSS vars (non-numeric array; see tokens.ts). */`,
        );
      }
      return;
    }
    if (typeof value === 'object' && value !== null) {
      for (const [key, child] of Object.entries(value)) {
        emitSection(key, child, path);
      }
      return;
    }
    const css = cssValue(path, value);
    if (css === null) {
      lines.push(
        `  /* ${path.join('.')} = ${JSON.stringify(value)} — not emitted as CSS vars (boolean; see tokens.ts). */`,
      );
      return;
    }
    lines.push(`  ${cssVarName(path)}: ${css};`);
  }

  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Tailwind 4 @theme generation
// ---------------------------------------------------------------------------

function generateTailwindTheme(json) {
  const lines = [
    HEADER('Tailwind 4 @theme bindings'),
    '',
    '/* Every entry is a var() reference into tokens.css: no value that is not in',
    ' * tokens.json ever reaches Tailwind, and renaming a token updates Tailwind',
    ' * consumers automatically (BRIEF 0.7 / plan D4).',
    ' */',
    '@theme {',
  ];
  for (const [name, value] of Object.entries(json.color)) {
    lines.push(`  --color-${name}: var(--mds-color-${name});`);
  }
  lines.push('');
  for (const el of json.space) {
    lines.push(`  --spacing-${el}: var(--mds-space-${el});`);
  }
  lines.push('');
  for (const [name, value] of Object.entries(json.radius)) {
    void value;
    lines.push(`  --radius-${name}: var(--mds-radius-${name});`);
  }
  lines.push('');
  lines.push('  --font-display: var(--mds-font-display);');
  lines.push('  --font-text: var(--mds-font-text);');
  lines.push('');
  for (const [name, spec] of Object.entries(json.type)) {
    if (typeof spec.size !== 'number') {
      // entity-initial has no single size (per-mark sizes) — no --text-* entry.
      lines.push(`  /* type.${name}: no single size (see --mds-type-${name}-size-by-mark-*). */`);
      continue;
    }
    lines.push(`  --text-${name}: var(--mds-type-${name}-size);`);
    lines.push(`  --text-${name}--line-height: var(--mds-type-${name}-line);`);
    lines.push(`  --text-${name}--font-weight: var(--mds-type-${name}-weight);`);
  }
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// tokens.ts generation
// ---------------------------------------------------------------------------

function generateTokensTs(json) {
  const literal = JSON.stringify(json, null, 2);
  return `${HEADER('typed token tree, TokenPath and getToken()')}
/**
 * The literal token tree (as const) mirrors tokens.json exactly. CSS values
 * live in tokens.css; this module is the TypeScript view of the same source.
 */
export const tokens = ${literal} as const;

export type Tokens = typeof tokens;

/** Dotted path to any leaf, e.g. 'color.canvas' or 'motion.press-in.ms'. */
export type TokenPath = PathOf<Tokens>;

type PathOf<T, Prefix extends string = ''> = T extends readonly unknown[]
  ? Prefix
  : T extends object
    ? { [K in keyof T & string]: PathOf<T[K], Prefix extends '' ? K : \`\${Prefix}.\${K}\`> }[keyof T & string]
    : Prefix;

/** Value type at the end of a TokenPath. */
export type TokenValue<P extends TokenPath> = TokenValueAt<Tokens, P>;

type TokenValueAt<T, P extends string> = P extends \`\${infer Head}.\${infer Rest}\`
  ? Head extends keyof T
    ? TokenValueAt<T[Head], Rest>
    : never
  : P extends keyof T
    ? T[P]
    : never;

/** Read a token by dotted path, e.g. getToken('motion.press-cancel-px'). */
export function getToken<P extends TokenPath>(path: P): TokenValue<P> {
  let node: unknown = tokens;
  for (const key of path.split('.')) {
    node = (node as Record<string, unknown>)[key];
  }
  return node as TokenValue<P>;
}

// Helper types derived from the token tree -------------------------------

/** Spacing scale values (BRIEF 7): 4 | 8 | 12 | 16 | 20 | 24 | 32 | 40 | 56. */
export type Space = (typeof tokens.space)[number];

/** Icon sizes (BRIEF 5.5) plus the ask-symbol sizes (tokens.size.ask-symbol). */
export type IconSize = (typeof tokens.size.icon)[number] | (typeof tokens.size)['ask-symbol'];

/** EntityMark sizes (BRIEF 5.4 / 23.5). */
export type EntityMarkSize = (typeof tokens.size.entity)[number];

/**
 * Semantic tone values (BRIEF 23.18). Colors come from tokens
 * (status-*-fg / status-*-bg); the tone union itself is part of the
 * unified property names, not of tokens.json.
 */
export type Tone = 'neutral' | 'info' | 'done' | 'waiting' | 'problem';

/** StatusBadge text kinds -> tone mapping (BRIEF 23.6). */
export type ToneTokenName = 'status-done' | 'status-waiting' | 'status-problem' | 'status-info' | 'status-neutral';

/** SaveState values (BRIEF 23.18). */
export type SaveStateValue = 'draft' | 'sending' | 'saved' | 'failed';
`;
}

// ---------------------------------------------------------------------------
// Write / check
// ---------------------------------------------------------------------------

const outputs = [
  { path: join(dsRoot, 'src', 'tokens', 'tokens.css'), content: generateTokensCss(readJson()) },
  { path: join(dsRoot, 'src', 'tokens', 'tailwind-theme.css'), content: generateTailwindTheme(readJson()) },
  { path: join(dsRoot, 'src', 'tokens', 'tokens.ts'), content: generateTokensTs(readJson()) },
];

function readJson() {
  return JSON.parse(readFileSync(tokensJsonPath, 'utf8'));
}

const check = process.argv.includes('--check');
let failed = false;
for (const { path, content } of outputs) {
  if (check) {
    let current = null;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // missing file -> diff
    }
    if (current !== content) {
      failed = true;
      console.error(`[tokens:check] MISMATCH: ${path}`);
      if (current === null) {
        console.error('  file does not exist (run `npm run tokens`)');
      } else {
        const currentLines = current.split('\n');
        const contentLines = content.split('\n');
        let shown = 0;
        for (let i = 0; i < Math.max(currentLines.length, contentLines.length) && shown < 10; i++) {
          if (currentLines[i] !== contentLines[i]) {
            console.error(`  line ${i + 1}:`);
            if (currentLines[i] !== undefined) console.error(`    - ${currentLines[i]}`);
            if (contentLines[i] !== undefined) console.error(`    + ${contentLines[i]}`);
            shown++;
          }
        }
        if (shown === 10) console.error('  …more differences');
      }
    } else {
      console.log(`[tokens:check] OK: ${path}`);
    }
  } else {
    writeFileSync(path, content, 'utf8');
    console.log(`[tokens] wrote ${path}`);
  }
}

if (check && failed) {
  console.error('[tokens:check] FAILED — generated output differs from files on disk.');
  process.exit(1);
}
